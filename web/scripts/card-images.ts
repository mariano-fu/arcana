const capitalize = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);
const pad = (n: number): string => String(n).padStart(2, '0');

export interface CardImageSource {
  key: string;
  /** Commons file title without the `File:` prefix. */
  file: string;
  /** English card name the Commons description must start with. */
  englishName: string;
}

export function cardImageSource(card: Pick<Card, 'key' | 'number' | 'suit'>): CardImageSource {
  if (card.suit === null) {
    const name = MAJOR_NAMES[card.number];
    if (name === undefined) throw new Error(`No major arcana name for ${card.key}`);
    return { key: card.key, file: `RWS1909 - ${pad(card.number)} ${name}.jpeg`, englishName: name };
  }
  const rank = RANK_NAMES[card.number - 1];
  if (rank === undefined || !SUITS.includes(card.suit)) {
    throw new Error(`No rank/suit name for ${card.key}`);
  }
  const suit = capitalize(card.suit);
  return {
    key: card.key,
    file: `RWS1909 - ${suit} ${pad(card.number)}.jpeg`,
    englishName: `${rank} of ${suit}`,
  };
}

/** The Commons fields the build reads, with HTML stripped. */
export interface CommonsFileInfo {
  /** Direct URL of the original upload. */
  url: string;
  /** Commons file page. */
  pageUrl: string;
  description: string;
  artist: string;
  license: string;
  credit: string;
}

export interface CardImageCredit extends CommonsFileInfo, CardImageSource {}

/** Throws unless the Commons metadata shows the expected card from the 1909 original. */
export function checkCommonsFile(source: CardImageSource, info: CommonsFileInfo): void {
  const problems: string[] = [];
  if (!info.description.startsWith(`${source.englishName} card from`)) {
    problems.push(`description is not for "${source.englishName}"`);
  }
  if (!/\boriginal 1909\b/.test(info.description)) {
    problems.push('description does not state an original 1909 deck');
  }
  if (info.license !== 'Public domain') problems.push(`license is "${info.license}"`);
  if (!info.artist.includes('Pamela Colman Smith')) problems.push(`artist is "${info.artist}"`);
  if (problems.length > 0) {
    throw new Error(`${source.key} (File:${source.file}): ${problems.join('; ')}`);
  }
}

export function stripHtml(html: string): string {
  return html
    .replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

const cell = (s: string): string => s.replace(/\|/g, '\\|');

export function renderCredits(credits: readonly CardImageCredit[]): string {
  const rows = credits.map((c) =>
    [
      `\`${c.key}\``,
      c.englishName,
      `[File:${cell(c.file)}](${c.pageUrl})`,
      `[original](${c.url})`,
      cell(c.license),
    ].join(' | '),
  );
  return [
    '# Card image credits',
    '',
    '<!-- Generated by `npm run build:card-images`. Do not edit by hand. -->',
    '',
    'Artwork: Pamela Colman Smith, for the Rider-Waite-Smith tarot deck (Rider & Son, London, 1909).',
    'Public domain (the artist died in 1951; PD-old-70-expired).',
    '',
    'Scans: the "RWS1909" set on Wikimedia Commons, an original 1909 "Roses & Lilies" printing',
    'scanned by Saskia Jansen from her personal collection',
    `(credit given on Commons: ${credits[0]?.credit ?? '—'}).`,
    'Each file below was checked against its Commons description, which must state the original',
    '1909 deck. The app ships resized WebP copies: `cards/thumb/<key>.webp` (160 px wide) and',
    '`cards/full/<key>.webp` (600 px wide).',
    '',
    '| Key | Card | Commons file | Source | License |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map((r) => `| ${r} |`),
    '',
  ].join('\n');
}
