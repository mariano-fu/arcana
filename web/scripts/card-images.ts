// Card image sources and checks for scripts/build-card-images.ts.
//
// Every image comes from the "RWS1909" set on Wikimedia Commons: an original 1909
// "Roses & Lilies" printing of the Rider-Waite-Smith deck (Pamela Colman Smith artwork),
// scanned by Saskia Jansen. The build refuses any file whose Commons description does not
// state the 1909 original, so a later or recolored edition cannot slip in.

import { SUITS, type Card } from '../src/seed/cards.ts';

