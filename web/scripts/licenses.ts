// Third-party licences shown in Ajustes → Acerca de: every package whose code ships to the
// device, with its full licence text (MIT and similar licences require the notice to travel
// with the code).
//
// "Ships" means the runtime `dependencies` in package.json and everything they pull in, plus
// the Workbox runtime that vite-plugin-pwa (a dev dependency) bundles into the service worker
// and the registration script. Dev dependencies are left out on purpose: they never reach her
// phone, and a dev-only bump must not make the committed list stale.

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** The committed list, regenerated by `npm run build:licenses`. */
export const LICENSES_PATH = new URL('../src/features/settings/licenses.json', import.meta.url);

/** Workbox packages that end up in `sw.js` / `workbox-*.js` and in `virtual:pwa-register`. */
export const WORKBOX_RUNTIME = ['workbox-precaching', 'workbox-window'] as const;

/**
 * Packages that ship no licence file but carry the notice in a header comment of this file
 * (checked by hand: astronomy-engine's MIT notice opens `astronomy.js`).
 */
export const HEADER_NOTICES: Record<string, string> = { 'astronomy-engine': 'astronomy.js' };

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i;

export interface PackageLicense {
  name: string;
  version: string;
  /** SPDX identifier from package.json, e.g. `MIT`, `Apache-2.0`. */
  license: string;
  /** Full licence and notice text, files joined by a blank line. */
  text: string;
}

export interface LicensesFile {
  packages: PackageLicense[];
}

interface PackageJson {
  name: string;
  version: string;
  license?: string | { type?: string };
  dependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
}

const readJson = (path: string) => JSON.parse(readFileSync(path, 'utf8')) as PackageJson;

/** Node's lookup: `node_modules/<name>` next to `from`, then in each parent up to `root`. */
function resolvePackage(name: string, from: string, root: string): string | null {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    if (dir === root || dirname(dir) === dir) return null;
  }
}

/** The first block comment of `source`, without the comment markers. */
export function headerComment(source: string): string | null {
  const match = /^\s*\/\*+([\s\S]*?)\*\//.exec(source);
  if (!match?.[1]) return null;
  const lines = match[1].split('\n').map((line) => line.replace(/^\s*\*?\s?/, '').trimEnd());
  return lines
    .filter((line) => line !== '@preserve')
    .join('\n')
    .trim();
}

function licenseText(name: string, dir: string): string {
  const header = HEADER_NOTICES[name];
  if (header !== undefined) {
    const text = headerComment(readFileSync(join(dir, header), 'utf8'));
    if (text === null || !/licen[cs]e/i.test(text)) {
      throw new Error(`${name}: no licence notice at the top of ${header}`);
    }
    return text;
  }
  const files = readdirSync(dir)
    .filter((file) => LICENSE_FILE.test(file))
    .sort((a, b) => a.localeCompare(b));
  if (files.length === 0) throw new Error(`${name}: no LICENSE, COPYING or NOTICE file`);
  return files.map((file) => readFileSync(join(dir, file), 'utf8').trim()).join('\n\n');
}

/**
 * Walks the runtime dependency tree from `root` (a folder with package.json and node_modules)
 * and returns each shipped package once, sorted by name. Type-only `@types/*` packages are
 * skipped. Throws on a missing package, licence identifier or licence text.
 */
export function collectLicenses(
  root: string,
  extraRoots: readonly string[] = WORKBOX_RUNTIME,
): LicensesFile {
  const pkg = readJson(join(root, 'package.json'));
  const queue = [...Object.keys(pkg.dependencies ?? {}), ...extraRoots].map((name) => ({
    name,
    from: root,
  }));
  const found = new Map<string, PackageLicense>();

  for (let next = queue.shift(); next; next = queue.shift()) {
    if (next.name.startsWith('@types/')) continue;
    const dir = resolvePackage(next.name, next.from, root);
    if (dir === null) throw new Error(`${next.name}: not installed (run npm ci)`);
    const meta = readJson(join(dir, 'package.json'));
    const key = `${meta.name}@${meta.version}`;
    if (found.has(key)) continue;
    const license = typeof meta.license === 'string' ? meta.license : meta.license?.type;
    if (!license) throw new Error(`${key}: no "license" in package.json`);
    found.set(key, {
      name: meta.name,
      version: meta.version,
      license,
      text: licenseText(meta.name, dir),
    });
    for (const dep of Object.keys({ ...meta.dependencies, ...meta.optionalDependencies })) {
      queue.push({ name: dep, from: dir });
    }
  }

  const packages = [...found.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
  return { packages };
}

/** The file's exact contents, so the staleness check can compare strings. */
export function renderLicenses(file: LicensesFile): string {
  return `${JSON.stringify(file, null, 2)}\n`;
}
